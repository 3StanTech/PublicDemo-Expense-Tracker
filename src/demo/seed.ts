function tx(
  id: string,
  partial: Omit<Transaction, 'id' | 'userId' | 'createdAt' | 'updatedAt' | 'recurringRuleId'> & {
    recurringRuleId?: string | null
    createdAt?: string
    updatedAt?: string
  },
): Transaction {
  return {
    id,
    userId: DEMO_USER_ID,
    recurringRuleId: partial.recurringRuleId ?? null,
    createdAt: partial.createdAt ?? TS_AUG,
    updatedAt: partial.updatedAt ?? partial.createdAt ?? TS_AUG,
    kind: partial.kind,
    status: partial.status,
    amountMinor: partial.amountMinor,
    occurredOn: partial.occurredOn,
    accountId: partial.accountId,
    transferAccountId: partial.transferAccountId,
    categoryId: partial.categoryId,
    payee: partial.payee,
    notes: partial.notes,
  }
}

